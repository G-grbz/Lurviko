def ui_text(key: str, **values: Any) -> str:
    template = _UI_TEXT.get(key, key)
    try:
        return template.format(**values) if values else template
    except Exception:
        return template


def ffmpeg_path() -> str:
    override = os.environ.get("GFILE_FFMPEG_PATH", "").strip()
    if override and Path(override).is_file():
        return override
    found = shutil.which("ffmpeg")
    if not found:
        raise UserVisibleError(ui_text("error_ffmpeg_missing"))
    return found


def ffprobe_path(auto_install: bool = False) -> str | None:
    del auto_install
    override = os.environ.get("GFILE_FFPROBE_PATH", "").strip()
    if override and Path(override).is_file():
        return override
    return shutil.which("ffprobe")


def third_party_subprocess_executable(args: list[str]) -> str | None:
    del args
    return None


def third_party_subprocess_env() -> dict[str, str]:
    env = os.environ.copy()
    # Child ffmpeg processes do not need the Python package search path.
    env.pop("PYTHONHOME", None)
    return env


def subprocess_common_kwargs() -> dict[str, Any]:
    kwargs: dict[str, Any] = {"text": True, "encoding": "utf-8", "errors": "replace"}
    if os.name == "nt":
        startupinfo = subprocess.STARTUPINFO()
        startupinfo.dwFlags |= subprocess.STARTF_USESHOWWINDOW
        startupinfo.wShowWindow = subprocess.SW_HIDE
        kwargs.update({"creationflags": getattr(subprocess, "CREATE_NO_WINDOW", 0), "startupinfo": startupinfo})
    return kwargs
