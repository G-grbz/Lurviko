class UserVisibleError(RuntimeError):
    """Expected runtime problem that is safe to show in the UI."""

class OperationCancelled(UserVisibleError):
    """Raised when a cancellable operation is stopped by the user."""


def app_config_dir() -> Path:
    if os.name == "nt":
        base = Path(os.environ.get("APPDATA", Path.home() / "AppData" / "Roaming"))
        return base / "g-file" / "subtitle-ai"
    return Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "g-file" / "subtitle-ai"


